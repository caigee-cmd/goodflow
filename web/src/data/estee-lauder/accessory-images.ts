const accessoryImageKey = (caseId: string, name: string) => `${caseId}::${name}`

const ACCESSORY_IMAGE_INDEX = new Map(
  ACCESSORY_IMAGES.map((entry) => [accessoryImageKey(entry.caseId, entry.name), entry]),
)

export function accessoryImageFor(caseId: string, name: string): AccessoryImageMapping {
  const found = ACCESSORY_IMAGE_INDEX.get(accessoryImageKey(caseId, name))
  if (!found) throw new Error(`Missing accessory image mapping for ${caseId} / ${name}`)
  return found
}

export function withAccessoryImages(cases: Case[]): Case[] {
  return cases.map((item) => ({
    ...item,
    items: item.items.map((piece) => {
      const visual = accessoryImageFor(item.id, piece.name)
      const next: CaseItem = {
        ...piece,
        image: visual.image,
        imageKind: visual.kind,
      }
      return next
    }),
  }))
}
